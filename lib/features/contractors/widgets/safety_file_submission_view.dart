import 'package:flutter/material.dart';
import 'package:flutter_riverpod/flutter_riverpod.dart';
import 'package:cloud_firestore/cloud_firestore.dart';
import 'package:cloud_functions/cloud_functions.dart';
import 'package:pdf/pdf.dart';
import 'package:pdf/widgets.dart' as pw;
import 'package:printing/printing.dart';
import '../models/safety_file_models.dart';
import '../../../core/providers/app_providers.dart';
import '../../../core/utils/ui_utils.dart';
import 'package:sentinel1/core/utils/tenant_firestore_extension.dart';
import 'document_review_dialog.dart';
import 'ai_prescreen_badge.dart';
import '../services/contractor_prescreen_service.dart';
import '../services/contractor_review_service.dart';
import 'finding_list_item.dart';
import 'finding_update_dialog.dart';

class SafetyFileSubmissionView extends ConsumerStatefulWidget {
  final String contractorId;
  final String projectId;

  const SafetyFileSubmissionView({
    super.key,
    required this.contractorId,
    required this.projectId,
  });

  @override
  ConsumerState<SafetyFileSubmissionView> createState() =>
      _SafetyFileSubmissionViewState();
}

class _SafetyFileSubmissionViewState
    extends ConsumerState<SafetyFileSubmissionView> {
  // Lazy, not a field initializer — a field initializer runs the instant createState() builds
  // the State object (i.e. on the very first pumpWidget() in a test), before any widget test can
  // intercept it via a Riverpod override. As a getter it's only evaluated when _generateReport()
  // actually runs (Download Report tapped), which widget tests can simply avoid tapping.
  FirebaseFunctions get _functions => FirebaseFunctions.instanceFor(region: 'europe-west1');
  bool _isGeneratingPdf = false;
  final Set<String> _preScreeningIds = {};

  Future<void> _updateFindingStatus(Finding finding, FindingStatus newStatus, String comment) async {
    try {
      final user = ref.read(userProfileProvider).valueOrNull;
      await ref.read(contractorReviewServiceProvider).updateFindingStatus(
            finding: finding,
            newStatus: newStatus,
            comment: comment,
            userId: user?.uid ?? '',
          );
      if (mounted) UIUtils.showToast(context, 'Finding updated', type: ToastType.success);
    } catch (e) {
      if (mounted) UIUtils.showToast(context, 'Error updating finding: $e', type: ToastType.error);
    }
  }

  Future<void> _triggerPreScreen(ContractorDocument doc) async {
    setState(() => _preScreeningIds.add(doc.id));
    try {
      await ref.read(contractorPrescreenServiceProvider).triggerPreScreen(doc.id, doc.url);
    } catch (e) {
      if (mounted) UIUtils.showToast(context, 'AI pre-screen failed: $e', type: ToastType.error);
    } finally {
      if (mounted) setState(() => _preScreeningIds.remove(doc.id));
    }
  }

  Future<void> _generateReport(String submissionId) async {
    setState(() => _isGeneratingPdf = true);
    try {
      final res = await _functions
          .httpsCallable('generateSafetyFileReport')
          .call({'submissionId': submissionId});

      final data = res.data as Map;
      final findingsData = data['findings'] as List;

      final pdf = pw.Document();

      pdf.addPage(
        pw.MultiPage(
          build:
              (context) => [
                pw.Header(level: 0, child: pw.Text('Safety File Audit Report')),
                pw.Text('Submission ID: $submissionId'),
                pw.Text('Generated At: ${data['generatedAt']}'),
                pw.Text('Generated By: ${data['generatedBy']}'),
                pw.SizedBox(height: 20),
                pw.Text(
                  'Findings:',
                  style: pw.TextStyle(
                    fontWeight: pw.FontWeight.bold,
                    fontSize: 18,
                  ),
                ),
                pw.SizedBox(height: 10),
                ...findingsData.map(
                  (f) => pw.Container(
                    margin: const pw.EdgeInsets.only(bottom: 10),
                    padding: const pw.EdgeInsets.all(10),
                    decoration: pw.BoxDecoration(
                      border: pw.Border.all(color: PdfColors.grey),
                    ),
                    child: pw.Column(
                      crossAxisAlignment: pw.CrossAxisAlignment.start,
                      children: [
                        pw.Text(
                          'Document ID: ${f['documentId']}',
                          style: pw.TextStyle(fontWeight: pw.FontWeight.bold),
                        ),
                        pw.Text('Type: ${f['type']}'),
                        pw.Text('Status: ${f['status']}'),
                        pw.Text('Description: ${f['description']}'),
                        pw.SizedBox(height: 5),
                        pw.Text('History:'),
                        ...(f['statusHistory'] as List).map(
                          (h) => pw.Text(
                            '- ${h['status']}: ${h['comment'] ?? ''}',
                          ),
                        ),
                      ],
                    ),
                  ),
                ),
              ],
        ),
      );

      await Printing.layoutPdf(
        onLayout: (PdfPageFormat format) async => pdf.save(),
      );
    } catch (e) {
      if (mounted) {
        UIUtils.showToast(context, 'Error generating report: $e');
      }
    } finally {
      if (mounted) setState(() => _isGeneratingPdf = false);
    }
  }

  @override
  Widget build(BuildContext context) {
    final db = ref.watch(firestoreProvider);

    return StreamBuilder<QuerySnapshot>(
      stream:
          db
              .tenantCollection(
                ref.watch(currentTenantIdProvider) ?? "",
                'safety_file_submissions',
              )
              .where('contractorId', isEqualTo: widget.contractorId)
              .where('projectId', isEqualTo: widget.projectId)
              .limit(1)
              .snapshots(),
      builder: (context, snapshot) {
        if (!snapshot.hasData) {
          return const Center(child: CircularProgressIndicator());
        }

        if (snapshot.data!.docs.isEmpty) {
          return const Center(
            child: Text('No Safety File Submission for this project yet.'),
          );
        }

        final submissionDoc = snapshot.data!.docs.first;
        final submissionId = submissionDoc.id;
        final submission = SafetyFileSubmission.fromFirestore(submissionDoc);

        return Column(
          crossAxisAlignment: CrossAxisAlignment.start,
          children: [
            Padding(
              padding: const EdgeInsets.all(16),
              child: Row(
                mainAxisAlignment: MainAxisAlignment.spaceBetween,
                children: [
                  Column(
                    crossAxisAlignment: CrossAxisAlignment.start,
                    children: [
                      Text(
                        'Safety File Submission',
                        style: Theme.of(context).textTheme.titleMedium,
                      ),
                      Text(
                        'Status: ${submission.status.name}',
                        style: TextStyle(
                          color: Theme.of(context).colorScheme.primary,
                        ),
                      ),
                    ],
                  ),
                  FilledButton.icon(
                    onPressed:
                        _isGeneratingPdf
                            ? null
                            : () => _generateReport(submissionId),
                    icon:
                        _isGeneratingPdf
                            ? const SizedBox(
                              width: 16,
                              height: 16,
                              child: CircularProgressIndicator(
                                strokeWidth: 2,
                                color: Colors.white,
                              ),
                            )
                            : const Icon(Icons.picture_as_pdf),
                    label: Text(
                      _isGeneratingPdf ? 'Generating...' : 'Download Report',
                    ),
                  ),
                ],
              ),
            ),
            const Divider(),
            Expanded(
              flex: 3,
              child: StreamBuilder<QuerySnapshot>(
                stream:
                    db
                        .tenantCollection(
                          ref.watch(currentTenantIdProvider) ?? "",
                          'contractor_documents',
                        )
                        .where('submissionId', isEqualTo: submissionId)
                        .snapshots(),
                builder: (ctx, docSnap) {
                  if (!docSnap.hasData) {
                    return const Center(child: CircularProgressIndicator());
                  }
                  final documents =
                      docSnap.data!.docs
                          .map((d) => ContractorDocument.fromFirestore(d))
                          .toList();

                  if (documents.isEmpty) {
                    return const Center(child: Text('No documents uploaded yet.'));
                  }

                  return ListView.builder(
                    padding: const EdgeInsets.all(16),
                    itemCount: documents.length,
                    itemBuilder: (context, i) {
                      final doc = documents[i];
                      return Card(
                        margin: const EdgeInsets.only(bottom: 12),
                        child: ListTile(
                          title: Text(doc.name),
                          subtitle: Column(
                            crossAxisAlignment: CrossAxisAlignment.start,
                            children: [
                              Text('Status: ${doc.status}'),
                              if (doc.feedback != null && doc.feedback!.isNotEmpty)
                                Text('Feedback: ${doc.feedback}'),
                              const SizedBox(height: 4),
                              Row(
                                children: [
                                  Expanded(child: AiPreScreenBadge(documentId: doc.id)),
                                  TextButton.icon(
                                    onPressed: _preScreeningIds.contains(doc.id)
                                        ? null
                                        : () => _triggerPreScreen(doc),
                                    icon: _preScreeningIds.contains(doc.id)
                                        ? const SizedBox(
                                            width: 14,
                                            height: 14,
                                            child: CircularProgressIndicator(strokeWidth: 2),
                                          )
                                        : const Icon(Icons.auto_awesome, size: 16),
                                    label: const Text('AI Pre-Screen'),
                                  ),
                                ],
                              ),
                            ],
                          ),
                          trailing: FilledButton.tonal(
                            onPressed: () => DocumentReviewDialog.show(context, doc),
                            child: const Text('Review'),
                          ),
                        ),
                      );
                    },
                  );
                },
              ),
            ),
            const Divider(),
            Padding(
              padding: const EdgeInsets.fromLTRB(16, 12, 16, 4),
              child: Text('Findings', style: Theme.of(context).textTheme.titleMedium),
            ),
            Expanded(
              flex: 2,
              child: StreamBuilder<QuerySnapshot>(
                stream: db
                    .tenantCollection(
                      ref.watch(currentTenantIdProvider) ?? "",
                      'findings',
                    )
                    .where('submissionId', isEqualTo: submissionId)
                    .snapshots(),
                builder: (ctx, findingSnap) {
                  if (!findingSnap.hasData) {
                    return const Center(child: CircularProgressIndicator());
                  }
                  final findings = findingSnap.data!.docs
                      .map((d) => Finding.fromFirestore(d))
                      .toList();

                  if (findings.isEmpty) {
                    return const Center(child: Text('No findings recorded.'));
                  }

                  return ListView.builder(
                    padding: const EdgeInsets.symmetric(horizontal: 16),
                    itemCount: findings.length,
                    itemBuilder: (context, i) {
                      final finding = findings[i];
                      return FindingListItem(
                        finding: finding,
                        onUpdateTap: () => FindingUpdateDialog.show(
                          context,
                          finding,
                          _updateFindingStatus,
                        ),
                      );
                    },
                  );
                },
              ),
            ),
          ],
        );
      },
    );
  }
}
